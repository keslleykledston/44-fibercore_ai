def _flag(migrated, tenant, on=True):
    with migrated.begin() as c:
        c.execute(text("SELECT set_config('app.tenant_id', :t, true)"), {"t": str(tenant)})
        c.execute(text("INSERT INTO tenant_features (tenant_id, feature, enabled) VALUES (:t,:f,:v) ON CONFLICT (tenant_id, feature) DO UPDATE SET enabled = :v"), {"t": tenant, "f": FEATURE, "v": on})


def _olt(migrated, tenant, edge, name="SEC-OLT-1", snmp_version=None):
    with migrated.begin() as c:
        return c.execute(text("INSERT INTO olts (tenant_id, edge_id, name, vendor, support_level, snmp_version) VALUES (:t,:e,:n,'huawei','identified',:v) RETURNING id"),
                         {"t": tenant, "e": edge, "n": name, "v": snmp_version}).scalar()


def _sqla(url):
    return create_engine(url.replace("postgresql://", "postgresql+psycopg://", 1))


class Ctx:
    """Tenant A, Edge a1 with a published (and by default confirmed) key, one OLT, the admin's headers."""

    def __init__(self, client, seed, inv, migrated, *, confirm=True, edge_key="a1", snmp_version=None):
        _flag(migrated, seed["A"])
        self.client, self.seed, self.inv, self.migrated = client, seed, inv, migrated
        self.tenant = seed["A"]
        self.edge = inv[edge_key]["edge"]
        self.ah = agent(client, inv, edge_key)
        self.h = hdr(client, "alice", seed, "A")
        self.priv, self.pub = H.new_edge_key()
        self.point = olt_secrets.b64url_decode(self.pub)
        self.key_id = olt_secrets.key_id(self.point)
        assert client.post("/v1/edge/seal-key", headers=self.ah, json={"public_key": self.pub}).status_code == 200
        if confirm:
            self.confirm()
        self.olt_name = "SEC-OLT-1"
        self.olt = _olt(migrated, seed["A"], self.edge, self.olt_name, snmp_version)

    def confirm(self):
        r = self.client.post(f"/v1/fleet/edges/{self.edge}/seal-key/confirm", headers=self.h, json={"key_id": self.key_id, "fingerprint": olt_secrets.fingerprint(self.point)})
        assert r.status_code == 200, r.text
        return r

    def make(self, kind="ssh_login", *, delivery_id=None, expires_in=1800, key_id=None, olt_name=None):
        did = str(delivery_id or uuid.uuid4())
        exp = int(time.time()) + expires_in
        aad = olt_secrets.aad(tenant_id=self.tenant, edge_id=self.edge, olt_name=olt_name or self.olt_name, kind=kind, delivery_id=did, key_id_=key_id or self.key_id, expires_at_unix=exp)
        plain = {"kind": kind, "username": USER, "password": PW} if kind == "ssh_login" else {"kind": kind, "community": COMMUNITY}
        blob = H.seal(self.point, json.dumps(plain, separators=(",", ":"), ensure_ascii=False).encode(), aad, key_id or self.key_id)
        return {"delivery_id": did, "kind": kind, "key_id": key_id or self.key_id, "expires_at": exp, "sealed": olt_secrets.b64url_encode(blob)}, aad

    def post(self, body, olt=None, headers=None):
        return self.client.post(f"/v1/fleet/olts/{olt or self.olt}/secret-deliveries", headers=headers or self.h, json=body)

    def next(self):
        return self.client.get("/v1/edge/secret-deliveries/next", headers=self.ah)

    def result(self, did, token, outcome="applied", code=None, headers=None):
        body = {"lease_token": str(token), "outcome": outcome}
        if code:
            body["code"] = code
        return self.client.post(f"/v1/edge/secret-deliveries/{did}/result", headers=headers or self.ah, json=body)

    def row(self, did):
        with self.migrated.begin() as c:
            return c.execute(text("SELECT status, has_blob, attempts, code, lease_token, lease_until FROM olt_secret_deliveries WHERE id = :i"), {"i": did}).one()

    def lapse(self, did):
        with self.migrated.begin() as c:
            c.execute(text("UPDATE olt_secret_deliveries SET lease_until = now() - interval '1 second' WHERE id = :i"), {"i": did})


