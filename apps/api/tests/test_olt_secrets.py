# ------------------------------------------------------------------ the database never lets the application read the blob
def test_the_application_role_cannot_read_the_blob_column_and_user_routes_never_call_the_reader(ctx, app_url, worker_url):
    c = ctx
    did = c.post(c.make()[0]).json()["id"]
    eng = _sqla(app_url)
    try:
        for sql in ("SELECT sealed FROM olt_secret_deliveries", "SELECT * FROM olt_secret_deliveries", "SELECT t.* FROM olt_secret_deliveries t",
                    "SELECT count(*) FROM olt_secret_deliveries WHERE sealed IS NOT NULL", "UPDATE olt_secret_deliveries SET status = status WHERE sealed IS NOT NULL",
                    "DELETE FROM olt_secret_deliveries", "UPDATE olt_secret_deliveries SET key_id = 'a'", "UPDATE olt_secret_deliveries SET expires_at = now()"):
            with pytest.raises(DBAPIError) as exc, eng.begin() as conn:
                conn.execute(text("SELECT set_config('app.tenant_id', :t, true)"), {"t": str(c.tenant)})
                conn.execute(text(sql))
            assert "permission denied" in str(exc.value), sql
        with eng.begin() as conn:   # what it MAY read: the state, only of its own tenant
            conn.execute(text("SELECT set_config('app.tenant_id', :t, true)"), {"t": str(c.tenant)})
            assert tuple(conn.execute(text("SELECT status, has_blob FROM olt_secret_deliveries WHERE id = :i"), {"i": did}).one()) == ("PENDING", True)
            assert conn.execute(text("SELECT app_secret_delivery_blob(:i, :l)"), {"i": did, "l": uuid.uuid4()}).scalar() is None   # a lease token nobody handed out reads nothing
            assert conn.execute(text("SELECT app_secret_delivery_blob(:i, NULL)"), {"i": did}).scalar() is None
    finally:
        eng.dispose()
    weng = make_engine(worker_url)   # the worker role has no grant on the table and cannot call the blob reader
