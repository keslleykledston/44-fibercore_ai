# ------------------------------------------------------------------ the contract, byte for byte
def test_the_independent_vectors_are_reproduced_byte_for_byte():
    v = H.VECTORS
    edge = H.scalar_key(v["edge"]["private_scalar_hex"])
    pt = H.point(edge)
    assert olt_secrets.b64url_encode(pt) == v["edge"]["public_point_b64url"]
    assert olt_secrets.parse_public_key(v["edge"]["public_point_b64url"]) == pt
    assert olt_secrets.key_id(pt) == v["edge"]["key_id"]
    assert olt_secrets.fingerprint(pt) == v["edge"]["fingerprint"]
    eph, nonce = H.scalar_key(v["ephemeral"]["private_scalar_hex"]), bytes.fromhex(v["ephemeral"]["nonce_hex"])
    for c in v["cases"]:
        parts = c["aad"].split("\n")
        assert olt_secrets.aad(tenant_id=parts[1], edge_id=parts[2], olt_name=parts[3], kind=parts[4], delivery_id=parts[5], key_id_=parts[6], expires_at_unix=int(parts[7])) == c["aad"]
        blob = H.seal(pt, c["plaintext_json"].encode(), c["aad"], v["edge"]["key_id"], ephemeral=eph, nonce=nonce)
        assert olt_secrets.b64url_encode(blob) == c["sealed_b64url"] and len(blob) == c["blob_len"]
        assert olt_secrets.parse_blob(c["sealed_b64url"]) == blob
        assert H.open_blob(edge, olt_secrets.b64url_decode(c["sealed_b64url"]), c["aad"], v["edge"]["key_id"]).decode() == c["plaintext_json"]


def test_the_delivery_signature_matches_the_vector_and_verifies():
    s = H.VECTORS["delivery_signature"]
    case = H.VECTORS["cases"][s["case_index"]]
    blob = olt_secrets.b64url_decode(case["sealed_b64url"])
    assert olt_secrets.delivery_message(case["aad"], blob).decode() == s["message_utf8"]
    key = Ed25519PrivateKey.from_private_bytes(bytes.fromhex(s["ed25519_seed_hex"]))
    sig = olt_secrets.sign_delivery(key, case["aad"], blob)
    assert sig == s["signature_b64url"]   # Ed25519 is deterministic: byte for byte
    Ed25519PublicKey.from_public_bytes(olt_secrets.b64url_decode(s["public_key_b64url"])).verify(olt_secrets.b64url_decode(sig), olt_secrets.delivery_message(case["aad"], blob))


def test_the_pure_helpers_refuse_what_the_contract_refuses():
    for bad in ("", "a", "a=", "ab+/", "ab cd", "AAAAA"):
        with pytest.raises(ValueError):
            olt_secrets.b64url_decode(bad)
    with pytest.raises(ValueError):
        olt_secrets.b64url_decode("AB")   # non-canonical trailing bits
    pt = olt_secrets.b64url_decode(H.VECTORS["edge"]["public_point_b64url"])
    for bad_point in (b"\x04" + b"\x00" * 64, b"\x02" + pt[1:33], pt[:-1]):
        with pytest.raises(ValueError):
            olt_secrets.parse_public_key(olt_secrets.b64url_encode(bad_point))
    blob = olt_secrets.b64url_decode(H.VECTORS["cases"][0]["sealed_b64url"])
    for bad_blob in (bytes([2]) + blob[1:], blob[:60], bytes([1, 4]) + b"\x00" * 200, b"x" * 3000):
        with pytest.raises(ValueError):
            olt_secrets.parse_blob(olt_secrets.b64url_encode(bad_blob))
    assert olt_secrets.normalize_fingerprint("9BDC c5ff-bbdf-3efc 1e04-064a-f580-05db") == "9bdcc5ffbbdf3efc1e04064af58005db"
    assert olt_secrets.normalize_fingerprint("9bdc") is None


