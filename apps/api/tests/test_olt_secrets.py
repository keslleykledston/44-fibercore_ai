    dup = c.make()[0]   # the same delivery_id twice
    assert c.post(dup).status_code == 202
    second = c.post(dup)
    assert (second.status_code, second.json()["detail"]) == (409, "delivery_id_taken")
    assert c.post(body, olt=uuid.uuid4()).status_code == 404   # an OLT that does not exist / belongs to another tenant: 404
    with migrated.begin() as conn:
        bolt = conn.execute(text("INSERT INTO olts (tenant_id, edge_id, name, vendor, support_level) VALUES (:t,:e,'SEC-OLT-B','huawei','identified') RETURNING id"), {"t": seed["B"], "e": inv["b1"]["edge"]}).scalar()
    assert c.post(c.make()[0], olt=bolt).status_code == 404
    assert client.get(f"/v1/fleet/olts/{bolt}/secret-deliveries", headers=c.h).status_code == 404


