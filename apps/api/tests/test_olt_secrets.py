def test_concurrent_pollers_draining_the_queue_keep_the_one_in_flight_rule(ctx):
    c = ctx
    for _ in range(5):
        assert c.post(c.make()[0]).status_code == 202
    other = _olt(c.migrated, c.tenant, c.edge, "SEC-OLT-2")
    for _ in range(3):
        assert c.post(c.make(olt_name="SEC-OLT-2")[0], olt=other).status_code == 202
    errors: list = []
    done: list = []

    def worker():
        cli = _new_client()
        try:
            while True:
                r = cli.get("/v1/edge/secret-deliveries/next", headers=c.ah)
                if r.status_code == 204:
                    return
                if r.status_code != 200:
                    errors.append(("next", r.status_code, r.text))
                    return
                d = r.json()
                rr = cli.post(f"/v1/edge/secret-deliveries/{d['id']}/result", headers=c.ah, json={"lease_token": d["lease_token"], "outcome": "applied"})
                if rr.status_code == 204:
                    done.append(d["id"])
                elif rr.status_code != 409:
                    errors.append(("result", rr.status_code))
                    return
        except Exception as exc:   # pragma: no cover
            errors.append(repr(exc))

    ts = [threading.Thread(target=worker) for _ in range(8)]
    for t in ts:
        t.start()
    for t in ts:
        t.join(timeout=90)
    assert not errors, errors
    with c.migrated.begin() as conn:
        statuses = [r.status for r in conn.execute(text("SELECT status FROM olt_secret_deliveries")).all()]
        assert statuses.count("DISPATCHED") == 0 and statuses.count("PENDING") == 0
        assert statuses.count("APPLIED") == 8 and len(set(done)) == 8
        assert conn.execute(text("SELECT count(*) FROM olt_secret_deliveries WHERE sealed IS NOT NULL")).scalar() == 0


