def test_key_lifecycle_pending_confirm_idempotent_and_rotation_cancels_what_waited(client, seed, inv, migrated):
    c = Ctx(client, seed, inv, migrated, confirm=False)
    k = client.get(f"/v1/fleet/edges/{c.edge}/seal-key", headers=c.h).json()
    assert (k["state"], k["key_id"], k["public_key"], k["fingerprint"]) == ("pending", c.key_id, c.pub, olt_secrets.fingerprint(c.point))
    assert abs(k["server_time"] - time.time()) < 5 and k["max_window_seconds"] == 3600 and k["tenant_id"] == str(c.tenant) and k["edge_id"] == str(c.edge)
    body, _ = c.make()
    r = c.post(body)   # an unconfirmed key is not trusted: no delivery can be posted
    assert (r.status_code, r.json()["detail"]) == (409, "seal_key_not_confirmed")
    assert client.post(f"/v1/fleet/edges/{c.edge}/seal-key/confirm", headers=c.h, json={"key_id": c.key_id, "fingerprint": "0000-0000-0000-0000-0000-0000-0000-0000"}).json()["detail"] == "fingerprint_mismatch"
    assert client.post(f"/v1/fleet/edges/{c.edge}/seal-key/confirm", headers=c.h, json={"key_id": "f" * 16, "fingerprint": olt_secrets.fingerprint(c.point)}).json()["detail"] == "seal_key_changed"
    assert client.get(f"/v1/fleet/edges/{c.edge}/seal-key", headers=c.h).json()["state"] == "pending"
    typed = olt_secrets.fingerprint(c.point).replace("-", " ").upper()   # spaces and upper case are forgiven
    assert client.post(f"/v1/fleet/edges/{c.edge}/seal-key/confirm", headers=c.h, json={"key_id": c.key_id, "fingerprint": typed}).json()["state"] == "confirmed"
    again = c.confirm().json()
    assert again["state"] == "confirmed" and again["confirmed_at"] is not None
    assert client.post("/v1/edge/seal-key", headers=c.ah, json={"public_key": c.pub}).json() == {"key_id": c.key_id, "state": "confirmed"}   # the same key again: nothing changes
    r = c.post(body)
    assert r.status_code == 202, r.text
    did = r.json()["id"]
    _, pub2 = H.new_edge_key()   # a NEW key: pending again, and what waited under the old key is cancelled with its blob erased
    r2 = client.post("/v1/edge/seal-key", headers=c.ah, json={"public_key": pub2})
    assert r2.status_code == 200 and r2.json()["state"] == "pending" and r2.json()["key_id"] != c.key_id
    row = c.row(did)
    assert (row.status, row.has_blob, row.code) == ("CANCELLED", False, "key_changed")
    assert client.get(f"/v1/fleet/edges/{c.edge}/seal-key", headers=c.h).json()["state"] == "pending"
    assert c.next().status_code == 204
    acts = {r.action: r.evidence_redacted for r in _audit(migrated)}
    assert acts["fleet.edge.seal_key.confirmed"]["key_id"] == c.key_id and acts["fleet.edge.seal_key.reported"]["cancelled_deliveries"] == 1


